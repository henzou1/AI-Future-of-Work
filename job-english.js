/* =========================================================
   BUILD ENGLISH DATA
   ========================================================= */

function getEnglishJobData(
    germanName
) {

    const mappedName =
        ENGLISH_JOB_NAMES[germanName]
        ||
        germanName;


    const aliases = new Set();


    if (
        ENGLISH_JOB_ALIASES[germanName]
    ) {

        ENGLISH_JOB_ALIASES[
            germanName
        ].forEach(
            alias => aliases.add(alias)
        );
    }


    ENGLISH_CATEGORY_RULES.forEach(
        rule => {

            if (
                rule.test(germanName)
            ) {

                rule.aliases.forEach(
                    alias =>
                        aliases.add(alias)
                );
            }

        }
    );


    /*
       The professional English name itself
       is always a searchable candidate.
    */

    if (
        mappedName !== germanName
    ) {

        aliases.add(
            mappedName
        );
    }


    return {

        nameEn:
            mappedName,

        aliasesEn:
            [
                ...aliases
            ]

    };
}


/* =========================================================
   APPLY TO JOB DATABASE
   ========================================================= */

if (
    typeof JOB_DATA !== "undefined" &&
    Array.isArray(JOB_DATA)
) {

    JOB_DATA.forEach(
        job => {

            const english =
                getEnglishJobData(
                    job.nameDe
                );


            /*
               Give the job its English name.
            */

            job.nameEn =
                english.nameEn;


            /*
               Also expose English aliases
               directly on the job object.
            */

            job.aliasesEn =
                english.aliasesEn;


            /*
               Merge the English information
               into JOB_CONTENT so that the
               existing job-checker search system
               automatically sees it.
            */

            if (
                typeof JOB_CONTENT !== "undefined"
            ) {

                const existing =
                    JOB_CONTENT[
                        job.nameDe
                    ]
                    ||
                    {};


                JOB_CONTENT[
                    job.nameDe
                ] = {

                    ...existing,

                    nameEn:
                        existing.nameEn
                        ||
                        english.nameEn,

                    aliasesEn:
                        [
                            ...new Set(
                                [
                                    ...(existing.aliasesEn || []),

                                    ...english.aliasesEn
                                ]
                            )
                        ]

                };
            }

        }
    );


    console.log(
        "English job data applied:",
        JOB_DATA.length,
        "jobs"
    );
}